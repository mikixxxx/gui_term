"""Generates the STerm icon: icon.png, icon.ico and ico.py (base64 PNG for the app).

Design: dark rounded terminal window, green ">_" prompt and an orange
UART-like square wave (serial line) at the bottom.
Run:  python make_icon.py   (needs Pillow)
"""
import base64
import io
from PIL import Image, ImageDraw

S = 1024                      # draw big, then downsample (anti-aliasing)
BG = (10, 16, 10, 255)
FRAME = (34, 160, 34, 255)
GREEN = (70, 225, 70, 255)
ORANGE = (255, 153, 0, 255)   # same as EOL marker color in the terminal

img = Image.new("RGBA", (S, S), (0, 0, 0, 0))
d = ImageDraw.Draw(img)

# window
d.rounded_rectangle((32, 32, S - 32, S - 32), radius=200, fill=BG, outline=FRAME, width=30)


def thick_line(points, width, color):
    d.line(points, fill=color, width=width, joint="curve")
    r = width // 2
    for x, y in (points[0], points[-1]):
        d.ellipse((x - r, y - r, x + r, y + r), fill=color)


# prompt ">"
thick_line([(250, 270), (470, 450), (250, 630)], 96, GREEN)
# cursor "_"
d.rounded_rectangle((540, 590, 800, 664), radius=18, fill=GREEN)

# serial line: UART-like frame (idle high, start bit low, data bits ...)
levels = [1, 0, 1, 0, 0, 1, 1, 0, 1]
x0, w = 170, 76
hi, lo = 790, 890
pts = []
prev = None
for i, lv in enumerate(levels):
    y = hi if lv else lo
    x = x0 + i * w
    if prev is not None and prev != y:
        pts.append((x, prev))
    pts.append((x, y))
    prev = y
pts.append((x0 + len(levels) * w, prev))
thick_line(pts, 34, ORANGE)

sizes = [16, 24, 32, 48, 64, 128, 256]
img.resize((256, 256), Image.LANCZOS).save("icon.png")
img.resize((256, 256), Image.LANCZOS).save("icon.ico", sizes=[(s, s) for s in sizes])

buf = io.BytesIO()
img.resize((128, 128), Image.LANCZOS).save(buf, format="PNG", optimize=True)
b64 = base64.b64encode(buf.getvalue()).decode("ascii")
with open("ico.py", "w") as f:
    f.write("# generated by make_icon.py - base64 encoded PNG (128x128) used as window icon\n")
    f.write('icon_base64 = (\n')
    for i in range(0, len(b64), 100):
        f.write(f'    "{b64[i:i + 100]}"\n')
    f.write(")\n")
print("done", len(b64))
