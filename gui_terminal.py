def on_connect_click():
    global srt, stop_event, rx_idle_timeout
    if not port_settings["port"]:
        terminal.append("app", "Configure port first!")
        return

    disconnect()   # close a previous connection (if any)

    sp.port = port_settings["port"]
    sp.baudrate = int(port_settings['baudrate'])
    sp.parity = parity_map[port_settings['parity']]
    sp.stopbits = stopbits_map[port_settings['stopbits']]
    sp.bytesize = bytesize_map[port_settings['databits']]
    sp.rtscts = port_settings['flow_control']
    sp.timeout = 0.1   # read() in the thread must not block forever

    try:
        sp.open()
    except (serial.SerialException, ValueError, OSError) as e:
        terminal.append("app", f"Failed to open port: {e}")
        return

    rx_idle_timeout = calc_idle_timeout()
    stop_event = threading.Event()
    srt =threading.Thread(target=serial_port_read_thread, args=(sp, stop_event), daemon=True)
    srt.start()
    terminal.append("app", "Connected")


def on_detach_click():
    if disconnect():
        terminal.append("app", "Disconnect")


def ctrlEvent(event):
    # allow Ctrl+C (copy) only; test the Ctrl bit, because event.state
    # also contains NumLock/CapsLock bits and differs between OSes
    if (event.state & 0x4) and event.keysym.lower() == "c":
        return
    return "break"


def on_enter(event):
    input_text = input_field.get()
    if input_text == "/port settings":
        terminal.append("app", "Port: " + str(port_settings['port'] or "(not set)"))
        terminal.append("app", "Baudrate: " + port_settings['baudrate'])
        terminal.append("app", "Parity: " + port_settings['parity'])
        terminal.append("app", "StopBits: " + port_settings['stopbits'])
        terminal.append("app", "DataBits: " + port_settings['databits'])
        terminal.append("app", "FlowCtrl: " + str(bool(port_settings["flow_control"])))
        terminal.append("app", "Line ending: " + eol_var.get())
    elif sp.is_open:
        data = input_text + eol_map[eol_var.get()]
        try:
            raw = data.encode("latin-1")
        except UnicodeEncodeError:
            terminal.append("app", "Text contains characters outside of latin-1, not sent.")
            return
        try:
            sp.write(raw)
        except (serial.SerialException, OSError) as e:
            terminal.append("app", f"Send failed: {e}")
            return
        terminal.append("sent", data)   # EOL is shown as a colored marker
    else:
        terminal.append("app", "Not connected!")
    input_field.delete(0, tk.END)


