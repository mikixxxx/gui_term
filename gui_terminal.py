port_settings = {
    "port": None,
    "baudrate": "9600",
    "parity": "None",
    "stopbits": "1",
    "databits": "8",
    "flow_control": False
}
parity_map = {
    "None": serial.PARITY_NONE,
    "Even": serial.PARITY_EVEN,
    "Odd": serial.PARITY_ODD,
    "Mark": serial.PARITY_MARK,
    "Space": serial.PARITY_SPACE
}
stopbits_map = {
    '1': serial.STOPBITS_ONE,
    '1.5': serial.STOPBITS_ONE_POINT_FIVE,
    '2': serial.STOPBITS_TWO
}
bytesize_map = {
    '5': serial.FIVEBITS,
    '6': serial.SIXBITS,
    '7': serial.SEVENBITS,
    '8': serial.EIGHTBITS
}
# line ending appended to every sent text
eol_map = {
    "None": "",
    "CR (\\r)": "\r",
    "LF (\\n)": "\n",
    "CRLF (\\r\\n)": "\r\n"
}
DEFAULT_EOL = "LF (\\n)"

sp = serial.Serial()
srt = threading.Thread()
stop_event = threading.Event()
rx_queue = queue.Queue()   # (shortmsg, msg, stream) from the reader thread -> GUI
last_rx_time = 0.0         # time.monotonic() of the last received chunk
rx_idle_timeout = 0.1      # seconds of silence that finish a line without EOL


def disconnect():
    """Stop the reader thread and close the port. Returns True if something was closed."""
    was_active = sp.is_open or srt.is_alive()
    stop_event.set()
    if srt.is_alive() and srt is not threading.current_thread():
        srt.join(1)
    if sp.is_open:
        try:
            sp.close()
        except (serial.SerialException, OSError):
            pass
    return was_active


def on_closing():
    disconnect()
    root.destroy()


def serial_port_read_thread(port, stop):
    # Runs in a separate thread -> it must NOT touch tkinter widgets,
    # data are passed to the GUI through rx_queue.
    carry = ""  # lone "\r" held back, so a "\r\n" split between two reads is not shown twice
    while not stop.is_set():
        try:
            raw = port.read(port.in_waiting or 1)   # blocks max. `timeout` seconds
        except (serial.SerialException, OSError, TypeError, ValueError) as e:
            if not stop.is_set():
                rx_queue.put(("app", f"Connection lost: {e}", False))
            break

        text = raw.decode('latin-1')
        if carry:
            text = carry + text   # when raw is empty this flushes the held "\r"
            carry = ""
        if raw and text.endswith("\r"):
            carry = "\r"
            text = text[:-1]
        if text:
            rx_queue.put(("received", text, True))


def calc_idle_timeout():
    """Silence on the line after which a line without EOL is considered finished.

    One character = start + data + parity + stop bits. The timeout is
    ~50 character times, but at least 0.1 s (USB adapters and the OS
    deliver data in bursts, a shorter value would split lines randomly).
    """
    try:
        bits = 1 + int(port_settings["databits"]) + float(port_settings["stopbits"])
        if port_settings["parity"] != "None":
            bits += 1
        char_time = bits / int(port_settings["baudrate"])
    except (ValueError, ZeroDivisionError, TypeError):
        char_time = 0.001
    return max(0.1, 50 * char_time)


def poll_queue():
    global last_rx_time
    try:
        while True:
            shortmsg, msg, stream = rx_queue.get_nowait()
            terminal.append(shortmsg, msg, stream)
            if stream:
                last_rx_time = time.monotonic()
    except queue.Empty:
        pass
    # received data without EOL + silence -> finish the line
    if terminal.has_open_line() and time.monotonic() - last_rx_time > rx_idle_timeout:
        terminal.close_line()
    root.after(20, poll_queue)


